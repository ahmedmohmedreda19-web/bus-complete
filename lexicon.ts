interface Entry { raw: string; key: string; stripped: string; custom?: boolean }

const exactIndex: Record<CatKey, Map<string, Entry>> = {} as never;
const letterIndex: Record<CatKey, Map<string, Entry[]>> = {} as never;
let totalWords = 0;

/** كلمات تنتهي بهاء حقيقية وليست تاء مربوطة (أسماء ذكور) */
const HAA_KEEP = new Set(["عبده", "حماده", "نبيه", "طه"]);

/** عرض جميل: الهاء في آخر الكلمة تتحول تاء مربوطة */
function prettify(raw0: string): string {
  return raw0.endsWith("ه") && !HAA_KEEP.has(raw0) ? raw0.slice(0, -1) + "ة" : raw0;
}

/** إدخال كلمة في الفهارس */
function indexWord(cat: CatKey, raw0: string, custom = false): boolean {
  const raw = prettify(raw0.trim());
  const key = normalizeArabic(raw);
  if (!key) return false;
  const stripped = stripAl(key);
  const exact = exactIndex[cat];
  const byLetter = letterIndex[cat];
  const entry: Entry = { raw, key, stripped, custom };
  if (!exact.has(key) || raw.length < exact.get(key)!.raw.length) exact.set(key, entry);
  if (stripped !== key && !exact.has(stripped)) exact.set(stripped, entry);
  const l = stripped.charAt(0);
  if (!byLetter.has(l)) byLetter.set(l, []);
  if (!byLetter.get(l)!.some((e) => e.key === key)) byLetter.get(l)!.push(entry);
  totalWords++;
  return true;
}

function build() {
  for (const cat of CATS) {
    exactIndex[cat.key] = new Map<string, Entry>();
    letterIndex[cat.key] = new Map<string, Entry[]>();
  }
  for (const cat of CATS) {
    const parts = RAW[cat.key].split("|").map((s) => s.trim()).filter(Boolean);
    for (const raw of parts) indexWord(cat.key, raw, false);
  }
}
build();

const BASE_DICTIONARY_SIZE = totalWords;
export const DICTIONARY_SIZE = BASE_DICTIONARY_SIZE;

