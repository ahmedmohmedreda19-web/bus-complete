const CUSTOM_KEY = "busComplete.customDict.v1";
const CUSTOM_EVT = "busComplete.customDictChanged";

export interface CustomWord { cat: CatKey; word: string; at: number }

let customWords: CustomWord[] = [];

function persistCustom() {
  try { localStorage.setItem(CUSTOM_KEY, JSON.stringify(customWords)); } catch { /* اتجاهل */ }
  window.dispatchEvent(new CustomEvent(CUSTOM_EVT));
}

/** تحميل كلمات اللاعب وقت بدء التشغيل */
function loadCustom() {
  try {
    const raw = localStorage.getItem(CUSTOM_KEY);
    if (!raw) return;
    const arr = JSON.parse(raw) as CustomWord[];
    if (!Array.isArray(arr)) return;
    const valid = CATS.map((c) => c.key);
    customWords = arr.filter((w) => w && valid.includes(w.cat) && typeof w.word === "string");
    for (const w of customWords) indexWord(w.cat, w.word, true);
  } catch { /* اتجاهل */ }
}
if (typeof window !== "undefined") loadCustom();

export const CUSTOM_DICT_EVENT = CUSTOM_EVT;

export function getCustomWords(): CustomWord[] {
  return [...customWords].sort((a, b) => b.at - a.at);
}

export function customCount(): number {
  return customWords.length;
}

export type AddResult = "added" | "exists" | "invalid" | "short";

/** إضافة كلمة لقاموس اللاعب — تتحسب «صح ١٠» بعد كده */
export function addCustomWord(cat: CatKey, word: string): AddResult {
  const raw = word.trim();
  if (!raw || !isArabicText(raw)) return "invalid";
  const n = normalizeArabic(raw);
  if (!isPlausibleWord(n)) return "short";
  const exact = exactIndex[cat];
  if (exact.has(n) || exact.has(stripAl(n))) return "exists";
  indexWord(cat, raw, true);
  customWords.push({ cat, word: prettify(raw), at: Date.now() });
  persistCustom();
  return "added";
}

/** حذف كلمة من قاموس اللاعب (وإعادة بناء الفهارس) */
export function removeCustomWord(cat: CatKey, word: string) {
  const key = normalizeArabic(word);
  customWords = customWords.filter((w) => !(w.cat === cat && normalizeArabic(w.word) === key));
  totalWords = 0;
  build();
  for (const w of customWords) indexWord(w.cat, w.word, true);
  persistCustom();
}

/** هل الكلمة دي من قاموس اللاعب؟ */
export function isCustomWord(cat: CatKey, word: string): boolean {
  const key = normalizeArabic(word);
  return customWords.some((w) => w.cat === cat && normalizeArabic(w.word) === key);
}

/** هل الكلمة معروفة أصلًا في الفئة دي؟ */
export function isKnownWord(cat: CatKey, word: string): boolean {
  const n = normalizeArabic(word);
  if (!n) return false;
  return exactIndex[cat].has(n) || exactIndex[cat].has(stripAl(n));
}

/** الحروف المتاحة للقرعة: لازم يكون فيها إجابات كافية في كل الفئات */
export const ELIGIBLE_LETTERS: string[] = (() => {
  const all = "ابتثجحخدذرزسشصضطظعغفقكلمنهوي".split("");
  return all.filter((l) => CATS.every((c) => (letterIndex[c.key].get(l)?.length ?? 0) >= 2));
})();

export function randomLetter(exclude?: string): string {
  let l = ELIGIBLE_LETTERS[Math.floor(Math.random() * ELIGIBLE_LETTERS.length)];
  let guard = 30;
  while (exclude && l === exclude && guard-- > 0) {
    l = ELIGIBLE_LETTERS[Math.floor(Math.random() * ELIGIBLE_LETTERS.length)];
  }
  return l;
}

/** الحكم على إجابة اللاعب */
export function judge(cat: CatKey, input: string, letter: string): Verdict {
  const rawInput = input.trim();
  const n = normalizeArabic(rawInput);
  if (!n) return { t: "bad", reason: "empty" };
  if (!isArabicText(rawInput)) return { t: "bad", reason: "invalid" };

  const first = stripAl(n).charAt(0);
  if (first !== letter) return { t: "bad", reason: "letter" };

  const exact = exactIndex[cat];
  const hit = exact.get(n) ?? exact.get(stripAl(n));
  // معروفة في الفئة دي — نعرضها زي ما اللاعب كتبها بالظبط (زي باقي القاموس)
  if (hit) return { t: "exact", pts: 10, display: rawInput };

  const candidates = letterIndex[cat].get(letter) ?? [];
  let best: Entry | null = null;
  let bestDist = 99;
  for (const e of candidates) {
    for (const k of [e.key, e.stripped]) {
      const d = levenshtein(n, k);
      if (d < bestDist) { bestDist = d; best = e; }
    }
  }
  if (best && bestDist <= correctionThreshold(n.length)) {
    // للكلمات القصيرة (٤ حروف ولا أقل): تصحيح حرف واحد فقط
    // وممنوع تبديل الطول بفرق أكتر من حرف واحد.
    const short = best.stripped.length <= 4;
    if (!short || (bestDist === 1 && Math.abs(n.length - best.stripped.length) <= 1)) {
      return { t: "fixed", pts: 8, display: best.raw };
    }
  }

  // مقبولة (كلمة عربية سليمة مش في القاموس) — تُحسب بس ٠ نقطة
  if (isPlausibleWord(n)) return { t: "ok", pts: 0, display: rawInput };
  return { t: "bad", reason: "invalid" };
}

/** عدد كلمات القاموس في فئة وحرف معيّن */
